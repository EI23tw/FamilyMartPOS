    private void cargarGraficoStock() {
        org.jfree.data.category.DefaultCategoryDataset dataset = new org.jfree.data.category.DefaultCategoryDataset();

        String sql = "SELECT nombre, stock FROM Productos WHERE estado = 1 ORDER BY stock ASC LIMIT 10";

        try (java.sql.Connection conn = com.twcorpororation.familymart.dao.Conexion.conectar(); java.sql.PreparedStatement pst = conn.prepareStatement(sql); java.sql.ResultSet rs = pst.executeQuery()) {

            while (rs.next()) {
                // Simplificamos la leyenda
                dataset.setValue(rs.getInt("stock"), "Unidades", rs.getString("nombre"));
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar datos del gráfico: " + e.getMessage());
            return;
        }

        org.jfree.chart.JFreeChart grafico = org.jfree.chart.ChartFactory.createBarChart(
                "Top 10: Alerta de Reposición",
                "", // Eje X vacío para que quede más limpio
                "Unidades Disponibles",
                dataset,
                org.jfree.chart.plot.PlotOrientation.HORIZONTAL,
                false, // Apagamos la leyenda inferior porque es redundante
                true,
                false
        );

        // --- AJUSTES VISUALES DEL GRÁFICO ---
        org.jfree.chart.plot.CategoryPlot plot = grafico.getCategoryPlot();
        org.jfree.chart.renderer.category.BarRenderer renderer = (org.jfree.chart.renderer.category.BarRenderer) plot.getRenderer();

        // 1. Limitar el grosor al 15% del espacio máximo (evita el bloque gigante)
        renderer.setMaximumBarWidth(0.15);

        // 2. Quitar el gradiente por defecto y aplicar un color sólido (Azul acero)
        renderer.setBarPainter(new org.jfree.chart.renderer.category.StandardBarPainter());
        renderer.setSeriesPaint(0, new java.awt.Color(54, 137, 191));

        // 3. Ocultar las líneas de la cuadrícula vertical para mayor limpieza
        plot.setDomainGridlinesVisible(false);
        // ------------------------------------

        org.jfree.chart.ChartPanel panelGrafico = new org.jfree.chart.ChartPanel(grafico);
        panelGrafico.setMouseWheelEnabled(true);

        pnlGraficoStock.setLayout(new java.awt.BorderLayout());
        pnlGraficoStock.removeAll();
        pnlGraficoStock.add(panelGrafico, java.awt.BorderLayout.CENTER);
        pnlGraficoStock.validate();
        pnlGraficoStock.repaint();
    }

