    private void cargarProductos() {
        // Configuramos las columnas de la tabla
        // Al crear el modelo, sobreescribimos el método isCellEditable para que retorne siempre falso
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel() {
            @Override
            public boolean isCellEditable(int row, int column) {
                return false; // Bloquea la edición directa en todas las celdas
            }
        };
        modelo.addColumn("ID");
        modelo.addColumn("Código");
        modelo.addColumn("Nombre");
        modelo.addColumn("Precio");
        modelo.addColumn("Stock");

        tblProductos.setModel(modelo);

        // Consulta: Solo productos con estado = 1 (Activos)
        String sql = "SELECT id_producto, codigo_barras, nombre, precio, stock FROM Productos WHERE estado = 1";

        try (Connection conn = Conexion.conectar(); PreparedStatement pstmt = conn.prepareStatement(sql); ResultSet rs = pstmt.executeQuery()) {

            // Recorremos los resultados y llenamos la tabla
            while (rs.next()) {
                Object[] fila = new Object[5];
                fila[0] = rs.getInt("id_producto");
                fila[1] = rs.getString("codigo_barras");
                fila[2] = rs.getString("nombre");
                fila[3] = rs.getDouble("precio");
                fila[4] = rs.getInt("stock");
                modelo.addRow(fila);
            }

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar productos: " + e.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarIndicadores() {
        String sqlVentas = "SELECT SUM(total) as Ingresos, COUNT(id_venta) as Transacciones, MAX(total) as Maximo, MIN(total) as Minimo, AVG(total) as Promedio FROM Ventas";
        String sqlStock = "SELECT COUNT(id_producto) as Agotados FROM Productos WHERE stock = 0 AND estado = 1";

        try (java.sql.Connection conn = com.twcorpororation.familymart.dao.Conexion.conectar()) {

            // 1. Cargar métricas de Ventas
            try (java.sql.PreparedStatement pst = conn.prepareStatement(sqlVentas); java.sql.ResultSet rs = pst.executeQuery()) {

                if (rs.next()) {
                    // Si no hay ventas, la BD devuelve null, que en Java getDouble lo lee como 0.0
                    double ingresos = rs.getDouble("Ingresos");
                    int transacciones = rs.getInt("Transacciones");
                    double maximo = rs.getDouble("Maximo");
                    double minimo = rs.getDouble("Minimo");
                    double promedio = rs.getDouble("Promedio");

                    lblIngresosTotales.setText(String.format("S/ %.2f", ingresos));
                    lblTotalTransacciones.setText(String.valueOf(transacciones));
                    lblTicketMaximo.setText(String.format("S/ %.2f", maximo));
                    lblTicketMinimo.setText(String.format("S/ %.2f", minimo));
                    lblTicketPromedio.setText(String.format("S/ %.2f", promedio));
                }
            }

            // 2. Cargar alerta de Stock (Productos agotados)
            try (java.sql.PreparedStatement pstStock = conn.prepareStatement(sqlStock); java.sql.ResultSet rsStock = pstStock.executeQuery()) {

                if (rsStock.next()) {
                    int agotados = rsStock.getInt("Agotados");
                    lblAlertasStock.setText(String.valueOf(agotados));
                }
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al cargar KPIs: " + e.getMessage(), "Error BD", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

    private void buscarProductos(String textoBusqueda) {
        javax.swing.table.DefaultTableModel modelo = new javax.swing.table.DefaultTableModel();
        modelo.addColumn("ID");
        modelo.addColumn("Código");
        modelo.addColumn("Nombre");
        modelo.addColumn("Precio");
        modelo.addColumn("Stock");

        tblProductos.setModel(modelo);

        // Consulta SQL con comodines (LIKE) para buscar coincidencias
        String sql = "SELECT id_producto, codigo_barras, nombre, precio, stock FROM Productos WHERE estado = 1 AND (nombre LIKE ? OR codigo_barras LIKE ?)";

        try (java.sql.Connection conn = com.twcorpororation.familymart.dao.Conexion.conectar(); java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

            // Los signos % indican que puede haber cualquier texto antes o después de la búsqueda
            pstmt.setString(1, "%" + textoBusqueda + "%");
            pstmt.setString(2, "%" + textoBusqueda + "%");

            java.sql.ResultSet rs = pstmt.executeQuery();

            while (rs.next()) {
                Object[] fila = new Object[5];
                fila[0] = rs.getInt("id_producto");
                fila[1] = rs.getString("codigo_barras");
                fila[2] = rs.getString("nombre");
                fila[3] = rs.getDouble("precio");
                fila[4] = rs.getInt("stock");
                modelo.addRow(fila);
            }

        } catch (java.sql.SQLException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "Error al buscar: " + e.getMessage(), "Error", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }

