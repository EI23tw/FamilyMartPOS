    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
        String codigo = txtCodigo.getText().trim();
        String nombre = txtNombre.getText().trim();
        String precioStr = txtPrecio.getText().trim();
        String stockStr = txtStock.getText().trim();

        // 1. Validación de campos vacíos
        if (codigo.isEmpty() || nombre.isEmpty() || precioStr.isEmpty() || stockStr.isEmpty()) {
            javax.swing.JOptionPane.showMessageDialog(this, "Todos los campos son obligatorios.", "Advertencia", javax.swing.JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            // 2. Validación de tipos de datos
            double precio = Double.parseDouble(precioStr);
            int stock = Integer.parseInt(stockStr);

            if (precio <= 0 || stock < 0) {
                javax.swing.JOptionPane.showMessageDialog(this, "El precio debe ser mayor a 0 y el stock no puede ser negativo.", "Rango Inválido", javax.swing.JOptionPane.WARNING_MESSAGE);
                return;
            }

            // 3. Inserción o Reactivación Inteligente
            // Si el código no existe, hace un INSERT. Si ya existe, hace un UPDATE reactivándolo.
            String sql = "INSERT INTO Productos (codigo_barras, nombre, precio, stock, estado) "
                    + "VALUES (?, ?, ?, ?, 1) "
                    + "ON DUPLICATE KEY UPDATE nombre = ?, precio = ?, stock = ?, estado = 1";

            try (java.sql.Connection conn = com.twcorpororation.familymart.dao.Conexion.conectar(); java.sql.PreparedStatement pstmt = conn.prepareStatement(sql)) {

                // Parámetros para el INSERT
                pstmt.setString(1, codigo);
                pstmt.setString(2, nombre);
                pstmt.setDouble(3, precio);
                pstmt.setInt(4, stock);

                // Parámetros para el UPDATE (por si el código de barras ya existía)
                pstmt.setString(5, nombre);
                pstmt.setDouble(6, precio);
                pstmt.setInt(7, stock);

                pstmt.executeUpdate();
                javax.swing.JOptionPane.showMessageDialog(this, "Producto guardado o reactivado correctamente.", "Éxito", javax.swing.JOptionPane.INFORMATION_MESSAGE);

                // 4. Actualizamos todas las tablas visuales
                cargarProductos();
                cargarProductosEliminados(); // Esto hará que el producto desaparezca de la tabla de eliminados
                cargarGraficoStock();
                limpiarCamposProductos();

            } catch (java.sql.SQLException e) {
                javax.swing.JOptionPane.showMessageDialog(this, "Error SQL: " + e.getMessage(), "Error SQL", javax.swing.JOptionPane.ERROR_MESSAGE);
            }

        } catch (NumberFormatException e) {
            javax.swing.JOptionPane.showMessageDialog(this, "El precio y el stock deben ser valores numéricos válidos.", "Error de Tipo de Dato", javax.swing.JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnGuardarActionPerformed

